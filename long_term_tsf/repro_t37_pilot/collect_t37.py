"""EXP-037 collector: build summary_t37.csv and RESULT_t37_pilot.md from
the archived evidence (logs/*.json, job-dir SUCCESS files). Every number in
the RESULT carries the evidence file it came from. Local-only (numpy/json);
run AFTER verify stages. --selfcheck exercises formatting with fabricated
records without touching real files.
"""
import argparse
import csv
import os
import sys

import t37_common as C


def safe(fn, default=None):
    try:
        return fn()
    except Exception:
        return default


def build_rows_a(vj):
    per = vj.get("monash", {}).get("per_subset", {})
    rows = []
    for ds, meta in C.SUBSETS.items():
        s = per.get(ds, {})
        rows.append({
            "task": "A_monash", "item": ds,
            "pred_len": s.get("pred_len"), "pred_len_expect": meta["pred_len"],
            "horizon_source": meta["horizon_source"],
            "n_series": s.get("n_series"),
            "autotune_P": s.get("autotune_p"), "P_expect": meta["p"],
            "visionts_mae": s.get("visionts_mae"),
            "naive_n1_mae": s.get("naive_n1_mae"), "naive_n2_mae": s.get("naive_n2_mae"),
            "ratio_vts_n1": s.get("ratio_n1"), "ratio_vts_n2": s.get("ratio_n2"),
            "paper_vts_mae": C.PAPER_T15[ds]["visionts"],
            "paper_naive_mae": C.PAPER_T15[ds]["naive"],
            "author_anchor_mae": C.AUTHOR_ANCHOR[ds]["mae"],
            "wall_sec_vision": s.get("wall_sec_vision"),
            "gpu_peak_mb_vision": s.get("gpu_peak_mb_vision"),
        })
    return rows


def build_rows_b(vj):
    fs = vj.get("fullshot", {})
    summ = fs.get("summary", {})
    timing = fs.get("timing", {})
    peak = fs.get("gpu_peak", {})
    rows = []
    for arm in ("all", "rand"):
        s = summ.get(arm, {})
        rows.append({
            "task": "B_etth1_96_seed2021", "item": "all" if arm == "all" else "rand_vm",
            "mse": s.get("mse_success"), "mae": s.get("mae_success"),
            "source": "this run (SUCCESS.txt; recompute-verified)",
            "wall_sec": safe(lambda: timing[arm]["wall_sec"]),
            "gpu_peak_mb": safe(lambda: peak[arm]["allocated_mb"]),
            "final_ckpt_sha256_16": safe(lambda: fs["final_ckpt_sha256"][arm][:16]),
            "paper_t22_4h_mean": "%.3f/%.3f" % C.PAPER_T22_ETTH1[
                "all" if arm == "all" else "rand"],
        })
    ln_ckpt = os.path.join(C.exp003_job(), "checkpoints", "_", "checkpoint.pth")
    rows.append({
        "task": "B_etth1_96_seed2021", "item": "ln_exp003_seed2021",
        "mse": C.LN_ANCHOR["mse"], "mae": C.LN_ANCHOR["mae"],
        "source": "EXP-003 anchor (BG9 gate)",
        "wall_sec": None, "gpu_peak_mb": None,
        "final_ckpt_sha256_16": C.sha256_of(ln_ckpt)[:16]
        if os.path.isfile(ln_ckpt) else None,
        "paper_t22_4h_mean": "%.3f/%.3f" % C.PAPER_T22_ETTH1["ln"],
    })
    rows.append({
        "task": "B_etth1_96_seed2021", "item": "freeze_exp033",
        "mse": C.FREEZE_ANCHOR["mse"], "mae": C.FREEZE_ANCHOR["mae"],
        "source": "EXP-033 anchor (BG9 gate)",
        "wall_sec": None, "gpu_peak_mb": None, "final_ckpt_sha256_16": None,
        "paper_t22_4h_mean": "%.3f/%.3f" % C.PAPER_T22_ETTH1["freeze"],
    })
    return rows


FIELDS_A = ["task", "item", "pred_len", "pred_len_expect", "horizon_source",
            "n_series", "autotune_P", "P_expect", "visionts_mae", "naive_n1_mae",
            "naive_n2_mae", "ratio_vts_n1", "ratio_vts_n2", "paper_vts_mae",
            "paper_naive_mae", "author_anchor_mae", "wall_sec_vision",
            "gpu_peak_mb_vision"]
FIELDS_B = ["task", "item", "mse", "mae", "source", "wall_sec", "gpu_peak_mb",
            "final_ckpt_sha256_16", "paper_t22_4h_mean"]
FIELDS_ALL = FIELDS_A + [f for f in FIELDS_B if f not in FIELDS_A]


def write_csv(path, rows, fields):
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in rows:
            w.writerow(r)


def fmt(v, nd=6):
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return ("%%.%df" % nd) % v
    return str(v)


def result_md(vj, rows_a, rows_b):
    mon = vj.get("monash", {})
    fs = vj.get("fullshot", {})
    L = []
    L.append("# EXP-037 RESULT: Monash two-subset zero-shot + ETTh1 All vs Rand-VM (pilot)\n")
    L.append("Generated by collect_t37.py from archived evidence only.\n")

    L.append("## A. Monash zero-shot (paper Table 15, official eval_gluonts harness)\n")
    L.append("| subset | pred_len | n_series | P | VisionTS MAE | Naive N1 | Naive N2 | VTS/N1 | VTS/N2 | paper VTS | paper Naive |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for r in rows_a:
        L.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            r["item"], fmt(r["pred_len"], 0), fmt(r["n_series"], 0),
            fmt(r["autotune_P"], 0), fmt(r["visionts_mae"], 4), fmt(r["naive_n1_mae"], 4),
            fmt(r["naive_n2_mae"], 4), fmt(r["ratio_vts_n1"], 4), fmt(r["ratio_vts_n2"], 4),
            fmt(r["paper_vts_mae"], 2), fmt(r["paper_naive_mae"], 2)))
    L.append("")
    L.append("Evidence: `logs/monash_<ds>.json` (split/pred_len/raw .tsf horizon/data version/"
             "autotune events), `logs/naive_<ds>.json` (N1/N2 + window-alignment check), "
             "`save_t37_monash/visionts_monash_<ds>.csv`, `save_t37_monash/naive_n{1,2}_monash_<ds>.csv` "
             "(N1/N2 exported separately from `logs/naive_<ds>.json`; the single naive_monash_<ds>.csv "
             "was ambiguous and removed per user verdict 2026-11-04); "
             "gates in `logs/verify_t37.json` (section monash).\n")
    L.append("Definitions: N1 = last imputed value repeated (Monash benchmark 'Naive' per "
             "Woo et al. 2024 / Godahewa et al. 2021; primary denominator); N2 = seasonal-naive "
             "with the subset's autotuned P tiled (sensitivity). VisionTS and Naive share the "
             "same test split objects, same imputation (`run.imputation_nan`), same "
             "evaluate_forecasts call and metric list.\n")

    L.append("## B. ETTh1 H=96 seed=2021: All (ImageNet init) vs Rand-VM (random init), full finetune\n")
    L.append("| arm | MSE | MAE | source | wall s | GPU peak MB | paper T22 (4H mean) |")
    L.append("|---|---|---|---|---|---|---|")
    for r in rows_b:
        L.append("| %s | %s | %s | %s | %s | %s | %s |" % (
            r["item"], fmt(r["mse"]), fmt(r["mae"]), r["source"],
            fmt(r["wall_sec"], 1), fmt(r["gpu_peak_mb"], 0), r["paper_t22_4h_mean"]))
    L.append("")
    L.append("Scope statements: (i) paper Table 22 values are means over H in {96,192,336,720}; "
             "this pilot reports H=96 only and does not reproduce the paper numbers. "
             "(ii) Rand-VM = same architecture, ALL weights randomly initialized, trained with "
             "exactly the All recipe (full finetune) — the training scope is this experiment's "
             "setting; the paper does not disclose the Rand-VM trainable set. "
             "(iii) init evidence: All initial vision_model == frozen ckpt tensors bitwise; "
             "Rand init recorded and differs (per-key counts in `logs/train_rand.json`); "
             "trainable name lists identical; full-epoch sampler index sha256 identical "
             "(BG4-BG7 in `logs/verify_t37.json`).\n")

    L.append("## Gates\n")
    for tag, section, gk in (("A", "monash", "subset"), ("B", "fullshot", "gate")):
        sec = vj.get(section, {})
        L.append("- %s: %d/%d gates pass (all_pass=%s) — see `logs/verify_t37.json`."
                 % (tag, sec.get("n_pass", 0), sec.get("n_gates", 0), sec.get("all_pass")))
    L.append("")

    L.append("## Budget estimate for the remaining scale-up\n")
    a_sum = mon.get("per_subset", {})
    for ds, s in a_sum.items():
        w, n = s.get("wall_sec_vision"), s.get("n_series")
        if w and n:
            L.append("- Monash %s: %.1f s for %d series -> %.2f s/series; remaining 27 subsets "
                     "scale as (measured s/series) x (each subset's series count); per-series cost "
                     "grows with context length and horizon." % (ds, w, n, w / n))
    bt = fs.get("timing", {}).get("all", {}).get("wall_sec")
    if bt:
        L.append("- ETTh1 H=96 full finetune: %.1f s/arm (202 train batches of 256 + val + "
                 "2785-window test); N further configs scale linearly at ~%.1f s each."
                 % (bt, bt))
    L.append("")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--selfcheck", action="store_true")
    args = ap.parse_args()

    if args.selfcheck:
        vj = {"monash": {"per_subset": {ds: {"pred_len": C.SUBSETS[ds]["pred_len"],
                                             "n_series": C.SUBSETS[ds]["series_info"],
                                             "autotune_p": C.SUBSETS[ds]["p"],
                                             "visionts_mae": 1.0, "visionts_mse": 2.0,
                                             "naive_n1_mae": 2.0, "naive_n2_mae": 2.5,
                                             "ratio_n1": 0.5, "ratio_n2": 0.4,
                                             "wall_sec_vision": 60.0,
                                             "gpu_peak_mb_vision": 1234}
                                        for ds in C.SUBSETS}},
              "fullshot": {"summary": {"all": {"mse_success": 0.5, "mae_success": 0.47},
                                       "rand": {"mse_success": 0.5, "mae_success": 0.47}},
                           "timing": {"all": {"wall_sec": 900.0}, "rand": {"wall_sec": 900.0}},
                           "gpu_peak": {"all": {"allocated_mb": 5000}, "rand": {"allocated_mb": 5000}},
                           "final_ckpt_sha256": {"all": "a" * 64, "rand": "b" * 64}}}
        out_dir = os.path.join("temp_selfcheck_t37")
        os.makedirs(out_dir, exist_ok=True)
        rows_a = build_rows_a(vj)
        rows_b = build_rows_b(vj)
        write_csv(os.path.join(out_dir, "summary_t37.csv"), rows_a + rows_b, FIELDS_ALL)
        md = result_md(vj, rows_a, rows_b)
        with open(os.path.join(out_dir, "RESULT_t37_pilot.md"), "w") as f:
            f.write(md)
        print("[t37] selfcheck OK -> %s" % out_dir)
        return

    vj = C.load_json(C.VERIFY_JSON)
    rows_a = build_rows_a(vj)
    rows_b = build_rows_b(vj)
    write_csv(os.path.join(C.LOG_DIR, "summary_t37.csv"), rows_a + rows_b,
              FIELDS_ALL)
    md = result_md(vj, rows_a, rows_b)
    with open(os.path.join(C.LOG_DIR, "RESULT_t37_pilot.md"), "w") as f:
        f.write(md)
    print("[t37] wrote %s and %s" % (os.path.join(C.LOG_DIR, "summary_t37.csv"),
                                     os.path.join(C.LOG_DIR, "RESULT_t37_pilot.md")))


if __name__ == "__main__":
    main()
